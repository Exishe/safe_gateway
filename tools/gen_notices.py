"""Generate THIRD_PARTY_NOTICES.md from package metadata (ADR 0008, ADR 0027).

Three lists, each read from the source of truth for that ecosystem:
- Python: the runtime dependency closure of safeguard-gateway, from installed
  metadata (the same walk `tools.check_licenses` does). Build tools such as
  PyInstaller are not in it.
- npm: the non-dev packages in `apps/web/package-lock.json` (the web UI bundle).
- Rust: `cargo metadata` for the desktop shell, following normal dependencies only
  (no build scripts, no dev dependencies), for every platform.

The notices that are written by hand (exceptions approved by the owner, models that
are downloaded rather than bundled) live in `tools/notices_manual.md`.
Run: `uv run python -m tools.gen_notices` to write the file, `--check` to fail when the
committed file is out of date.
"""

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from importlib import metadata
from pathlib import Path

from tools.check_licenses import (
    _RANK,
    PROJECT,
    Policy,
    Status,
    _classify_metadata,
    _classify_name,
    load_dist_info,
    load_policy,
    runtime_closure,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"
MANUAL = Path(__file__).with_name("notices_manual.md")
WEB_LOCK = ROOT / "apps" / "web" / "package-lock.json"
DESKTOP_MANIFEST = ROOT / "apps" / "desktop" / "src-tauri" / "Cargo.toml"
GENERATED_BY = "generated by `uv run python -m tools.gen_notices`"


@dataclass(frozen=True, order=True)
class Entry:
    name: str
    version: str
    license: str


def python_entries() -> list[Entry]:
    policy = load_policy()
    entries = []
    for name in runtime_closure(PROJECT):
        dist = load_dist_info(name)
        _, reason = _classify_metadata(dist, policy)
        label = reason.split(": ", 1)[-1]
        entries.append(Entry(dist.name, metadata.version(name), label))
    return sorted(entries, key=lambda e: e.name.lower())


def npm_entries(lock_path: Path) -> list[Entry]:
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    entries = []
    for path, meta in lock["packages"].items():
        if not path or meta.get("dev"):
            continue
        name = path.rsplit("node_modules/", 1)[-1]
        entries.append(Entry(name, meta["version"], meta.get("license", "UNKNOWN")))
    return sorted(entries, key=lambda e: e.name.lower())


def rust_entries(cargo_metadata: dict) -> list[Entry]:
    """Packages reachable from the root through normal (non-build, non-dev) edges."""
    nodes = {node["id"]: node for node in cargo_metadata["resolve"]["nodes"]}
    packages = {package["id"]: package for package in cargo_metadata["packages"]}
    root = cargo_metadata["resolve"]["root"]
    seen: set[str] = set()
    queue = [root]
    while queue:
        current = queue.pop()
        for dep in nodes[current]["deps"]:
            if any(kind["kind"] is None for kind in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                queue.append(dep["pkg"])
    entries = [
        Entry(p["name"], p["version"], p.get("license") or "UNKNOWN")
        for pid, p in packages.items()
        if pid in seen
    ]
    return sorted(entries, key=lambda e: e.name.lower())


_TOKEN = re.compile(r"\(|\)|\bAND\b|\bOR\b|[^\s()]+(?:\s+WITH\s+[^\s()]+)?", re.IGNORECASE)


def _expression_status(expression: str, policy: Policy) -> Status:
    """OR takes the best alternative, AND the worst part; parentheses nest.

    `tools.check_licenses` stops at nested expressions; Rust crates have them
    ("(MIT OR Apache-2.0) AND Unicode-3.0").
    """
    tokens = _TOKEN.findall(expression.replace("/", " OR "))
    position = 0

    def take() -> str | None:
        nonlocal position
        piece = tokens[position] if position < len(tokens) else None
        position += 1
        return piece

    def peek() -> str | None:
        return tokens[position] if position < len(tokens) else None

    def atom() -> Status:
        piece = take()
        if piece == "(":
            inner = either()
            take()  # the closing parenthesis
            return inner
        return _classify_name(piece or "", policy)

    def both() -> Status:
        parts = [atom()]
        while (peek() or "").upper() == "AND":
            take()
            parts.append(atom())
        return max(parts, key=_RANK.__getitem__)

    def either() -> Status:
        parts = [both()]
        while (peek() or "").upper() == "OR":
            take()
            parts.append(both())
        return min(parts, key=_RANK.__getitem__)

    return either()


def rust_problems(entries: list[Entry]) -> list[str]:
    """Crates whose license expression has no allowed alternative (hard rule 1)."""
    policy = load_policy()
    problems = []
    for entry in entries:
        # Older crates write "MIT/Apache-2.0" for "MIT OR Apache-2.0".
        status = _expression_status(entry.license, policy)
        if status != "allowed":
            problems.append(f"{entry.name}: {entry.license} ({status})")
    return problems


def cargo_metadata(manifest: Path) -> dict:
    command = [
        "cargo",
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--manifest-path",
        str(manifest),
    ]
    result = subprocess.run(command, check=True, capture_output=True, text=True)  # noqa: S603
    return json.loads(result.stdout)


def _table(entries: list[Entry]) -> str:
    rows = ["| Package | Version | License |", "|---------|---------|---------|"]
    rows += [
        f"| {e.name} | {e.version} | {e.license} |"
        for e in sorted(entries, key=lambda e: e.name.lower())
    ]
    return "\n".join(rows)


def render(manual: str, python: list[Entry], npm: list[Entry], rust: list[Entry]) -> str:
    parts = [
        "# Third-party notices",
        "",
        (
            "SafeGuard Gateway ships third-party software under the licenses below. The "
            f"tables are {GENERATED_BY}; do not edit them by hand. The notices above them "
            "are kept by hand in `tools/notices_manual.md`."
        ),
        "",
        manual.strip(),
        "",
        f"## Python packages in the sidecar ({len(python)})",
        "",
        (
            "The runtime closure of `safeguard-gateway`. The sidecar build (PyInstaller) is a "
            "build tool and is not shipped."
        ),
        "",
        _table(python),
        "",
        f"## npm packages in the web UI ({len(npm)})",
        "",
        _table(npm),
        "",
        f"## Rust crates in the desktop shell ({len(rust)})",
        "",
        "Normal dependencies of `apps/desktop/src-tauri`, for all platforms.",
        "",
        _table(rust),
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    rust = rust_entries(cargo_metadata(DESKTOP_MANIFEST))
    problems = rust_problems(rust)
    for problem in problems:
        print(f"rust license: {problem}")
    if problems:
        return 1
    text = render(MANUAL.read_text(encoding="utf-8"), python_entries(), npm_entries(WEB_LOCK), rust)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print("THIRD_PARTY_NOTICES.md is out of date; run `uv run python -m tools.gen_notices`")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
