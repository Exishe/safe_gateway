"""THIRD_PARTY_NOTICES.md generation: the pure parts, on small hand-made inputs."""

import json
from pathlib import Path

from tools.gen_notices import (
    Entry,
    npm_entries,
    render,
    rust_entries,
    rust_problems,
)


def test_npm_entries_list_shipped_packages_only(tmp_path: Path) -> None:
    lock = {
        "packages": {
            "": {"name": "root"},
            "node_modules/react": {"version": "19.0.0", "license": "MIT"},
            "node_modules/@radix-ui/react-slot": {"version": "1.5.0", "license": "MIT"},
            "node_modules/vite": {"version": "8.0.0", "license": "MIT", "dev": True},
        }
    }
    path = tmp_path / "package-lock.json"
    path.write_text(json.dumps(lock), encoding="utf-8")
    assert npm_entries(path) == [
        Entry("@radix-ui/react-slot", "1.5.0", "MIT"),
        Entry("react", "19.0.0", "MIT"),
    ]


def _package(name: str, license_: str | None = "MIT") -> dict[str, object]:
    return {"id": f"{name} 1.0", "name": name, "version": "1.0.0", "license": license_}


def test_rust_entries_follow_normal_dependencies_only() -> None:
    metadata = {
        "packages": [
            _package("app"),
            _package("serde"),
            _package("cc", "Apache-2.0 OR MIT"),
            _package("testing-only"),
            _package("nolicense", None),
        ],
        "resolve": {
            "root": "app 1.0",
            "nodes": [
                {
                    "id": "app 1.0",
                    "deps": [
                        {"pkg": "serde 1.0", "dep_kinds": [{"kind": None}]},
                        {"pkg": "cc 1.0", "dep_kinds": [{"kind": "build"}]},
                        {"pkg": "testing-only 1.0", "dep_kinds": [{"kind": "dev"}]},
                        {"pkg": "nolicense 1.0", "dep_kinds": [{"kind": None}]},
                    ],
                },
                {"id": "serde 1.0", "deps": []},
                {"id": "cc 1.0", "deps": []},
                {"id": "testing-only 1.0", "deps": []},
                {"id": "nolicense 1.0", "deps": []},
            ],
        },
    }
    assert rust_entries(metadata) == [
        Entry("nolicense", "1.0.0", "UNKNOWN"),
        Entry("serde", "1.0.0", "MIT"),
    ]


def test_render_is_sorted_and_marks_where_each_list_came_from() -> None:
    text = render(
        manual="## regex\n\nkept by hand.\n",
        python=[Entry("zeta", "1", "MIT"), Entry("alpha", "2", "Apache-2.0")],
        npm=[Entry("react", "19", "MIT")],
        rust=[Entry("serde", "1", "Apache-2.0 OR MIT")],
    )
    assert text.startswith("# Third-party notices")
    assert "kept by hand." in text
    assert text.index("alpha") < text.index("zeta")
    assert "| serde | 1 | Apache-2.0 OR MIT |" in text
    assert "generated by `uv run python -m tools.gen_notices`" in text
    assert text.endswith("\n")


def test_rust_license_check_accepts_permissive_and_flags_the_rest() -> None:
    entries = [
        Entry("a", "1", "MIT/Apache-2.0"),
        Entry("b", "1", "MIT OR Apache-2.0 OR LGPL-2.1-or-later"),
        Entry("c", "1", "Unicode-3.0"),
        Entry("d", "1", "GPL-3.0-only"),
        Entry("e", "1", "UNKNOWN"),
        Entry("f", "1", "MPL-2.0"),
        Entry("g", "1", "(MIT OR Apache-2.0) AND Unicode-3.0"),
        Entry("h", "1", "(MIT OR Apache-2.0) AND GPL-2.0-only"),
    ]
    problems = rust_problems(entries)
    assert [problem.split(":")[0] for problem in problems] == ["d", "e", "h"]
